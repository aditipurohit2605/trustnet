def get_provenance_header(repo_root: Path) -> Tuple[str, str]:
    """Retrieves commit hash and primary config hash for embedding in table comments."""
    freeze_manifest = repo_root / "outputs" / "final" / "freeze_manifest.json"
    ts = "frozen"
    commit = "unknown_commit"
    config_hash = "unknown_config_hash"
    if freeze_manifest.exists():
        try:
            with open(freeze_manifest, "r", encoding="utf-8") as f:
                data = json.load(f)
                commit = data.get("git", {}).get("head_commit", commit)
                configs = data.get("configs", {})
                config_hash = configs.get("stage7_calibration.yaml", configs.get("stage6_fusion.yaml", "recorded"))
                ts = data.get("timestamp") or ts
        except Exception:
            pass

    tex_comment = f"% Generated by TrustNet Stage 12 | Freeze Commit: {commit[:10]} | Config SHA-256: {config_hash[:12]} | Timestamp: {ts}\n"
    md_comment = f"<!-- TrustNet Stage 12 Provenance: Freeze Commit: {commit[:10]}, Config Hash: {config_hash[:12]} -->\n\n"
    return tex_comment, md_comment


def load_prediction_records(predictions_path: Path) -> List[Dict[str, Any]]:
    """Loads per-sample prediction records strictly from JSONL format."""
    records = []
    if predictions_path.exists():
        with open(predictions_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    records.append(json.loads(line))
    return records


def generate_main_comparison_table(
    predictions: List[Dict[str, Any]],
    output_dir: Path,
    repo_root: Path,
) -> None:
    """Table 1: Main System Performance Comparison across modalities and calibration."""
    tex_hdr, md_hdr = get_provenance_header(repo_root)

    # Filter by variant and calibrated state
    systems = [
        ("Text-Only Baseline", "text_only", "uncalibrated"),
        ("Multimodal (Text + Image)", "text_image", "uncalibrated"),
        ("Multimodal + Retrieval (Full)", "full", "uncalibrated"),
        ("Full + Calibrated (Temp)", "full", "temperature"),
        ("Full + Deep Ensemble Temp", "full", "ensemble_temperature"),
    ]

    label2idx = {"verified": 0, "contradicted": 1, "insufficient_evidence": 2}
    rows = []

    for label, var, cal in systems:
        subset = [r for r in predictions if r.get("variant") == var and r.get("calibration_mode") == cal]
        if not subset:
            # Fallback mock or defaults for display
            rows.append({
                "System": label, "Macro_F1": "0.000", "Accuracy": "0.000",
                "ECE": "0.000", "AURC": "0.000", "Coverage_5pct": "0.0%",
            })
            continue

        y_true = np.array([label2idx.get(r["gold_verdict"], 2) for r in subset])
        y_pred = np.array([label2idx.get(r["effective_verdict"], 2) for r in subset])
        probs = np.array([
            [r["probabilities"].get("verified", 0.33),
             r["probabilities"].get("contradicted", 0.33),
             r["probabilities"].get("insufficient_evidence", 0.34)]
            for r in subset
        ])

        acc = compute_accuracy(y_true, y_pred)
        f1 = compute_macro_f1(y_true, y_pred)
        ece = compute_ece(y_true, probs, n_bins=5)
        aurc = compute_aurc(y_true, probs)
        cov = compute_coverage_at_target_error(y_true, probs, target_error=0.05)

        rows.append({
            "System": label,
            "Macro_F1": f"{f1:.3f}",
            "Accuracy": f"{acc:.3f}",
            "ECE": f"{ece:.3f}",
            "AURC": f"{aurc:.3f}",
            "Coverage_5pct": f"{cov * 100:.1f}%",
        })

    # LaTeX Generation
    tex_path = output_dir / "table1_main_comparison.tex"
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write(tex_hdr)
        f.write("\\begin{table}[t]\n\\centering\n\\small\n")
        f.write("\\caption{Main system performance comparison on the test split across modalities, retrieval, and calibration.}\n")
        f.write("\\label{tab:main_comparison}\n")
        f.write("\\begin{tabular}{lccccc}\n\\toprule\n")
        f.write("System & Macro-F1 & Accuracy & ECE $\\downarrow$ & AURC $\\downarrow$ & Cov@5\\% \\\\\n\\midrule\n")
        for r in rows:
            f.write(f"{r['System']} & {r['Macro_F1']} & {r['Accuracy']} & {r['ECE']} & {r['AURC']} & {r['Coverage_5pct']} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")

    # Markdown Generation
    md_path = output_dir / "table1_main_comparison.md"
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md_hdr)
        f.write("### Table 1: Main System Performance Comparison\n\n")
        f.write("| System | Macro-F1 | Accuracy | ECE | AURC | Coverage @ 5% Error |\n")
        f.write("| :--- | :---: | :---: | :---: | :---: | :---: |\n")
        for r in rows:
            f.write(f"| {r['System']} | {r['Macro_F1']} | {r['Accuracy']} | {r['ECE']} | {r['AURC']} | {r['Coverage_5pct']} |\n")


