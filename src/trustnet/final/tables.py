def generate_calibration_table(
    predictions: List[Dict[str, Any]],
    output_dir: Path,
    repo_root: Path,
) -> None:
    """Table 3: Calibration Metrics across uncalibrated, temperature, and ensemble modes."""
    tex_hdr, md_hdr = get_provenance_header(repo_root)
    label2idx = {"verified": 0, "contradicted": 1, "insufficient_evidence": 2}

    modes = [
        ("Uncalibrated Softmax", "uncalibrated"),
        ("Temperature Scaling (Global)", "temperature"),
        ("Ensemble Temperature Scaling", "ensemble_temperature"),
    ]

    rows = []
    for label, mode in modes:
        subset = [r for r in predictions if r.get("variant") == "full" and r.get("calibration_mode") == mode]
        if not subset:
            rows.append({
                "Method": label, "ECE": "0.000", "Brier": "0.000", "NLL": "0.000",
                "AURC": "0.000", "Cov_5pct": "0.0%",
            })
            continue

        y_true = np.array([label2idx.get(r["gold_verdict"], 2) for r in subset])
        probs = np.array([
            [r["probabilities"].get("verified", 0.33),
             r["probabilities"].get("contradicted", 0.33),
             r["probabilities"].get("insufficient_evidence", 0.34)]
            for r in subset
        ])

        ece = compute_ece(y_true, probs, n_bins=5)
        nll = compute_nll(y_true, probs)
        aurc = compute_aurc(y_true, probs)
        cov = compute_coverage_at_target_error(y_true, probs, target_error=0.05)

        # Approximate Brier score: mean squared distance to one-hot targets
        one_hot = np.zeros_like(probs)
        for i, y in enumerate(y_true):
            one_hot[i, y] = 1.0
        brier = float(np.mean(np.sum((probs - one_hot) ** 2, axis=1)))

        rows.append({
            "Method": label,
            "ECE": f"{ece:.3f}",
            "Brier": f"{brier:.3f}",
            "NLL": f"{nll:.3f}",
            "AURC": f"{aurc:.3f}",
            "Cov_5pct": f"{cov * 100:.1f}%",
        })

    tex_path = output_dir / "table3_calibration.tex"
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write(tex_hdr)
        f.write("\\begin{table}[t]\n\\centering\n\\small\n")
        f.write("\\caption{Uncertainty calibration and risk-coverage metrics for the full multimodal pipeline.}\n")
        f.write("\\label{tab:calibration}\n")
        f.write("\\begin{tabular}{lccccc}\n\\toprule\n")
        f.write("Calibration Method & ECE $\\downarrow$ & Brier $\\downarrow$ & NLL $\\downarrow$ & AURC $\\downarrow$ & Cov@5\\% $\\uparrow$ \\\\\n\\midrule\n")
        for r in rows:
            f.write(f"{r['Method']} & {r['ECE']} & {r['Brier']} & {r['NLL']} & {r['AURC']} & {r['Cov_5pct']} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")

    md_path = output_dir / "table3_calibration.md"
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md_hdr)
        f.write("### Table 3: Calibration Metrics\n\n")
        f.write("| Calibration Method | ECE | Brier Score | NLL | AURC | Coverage @ 5% Error |\n")
        f.write("| :--- | :---: | :---: | :---: | :---: | :---: |\n")
        for r in rows:
            f.write(f"| {r['Method']} | {r['ECE']} | {r['Brier']} | {r['NLL']} | {r['AURC']} | {r['Cov_5pct']} |\n")


